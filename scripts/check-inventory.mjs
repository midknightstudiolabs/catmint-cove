import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
const fn=n=>html.match(new RegExp('function '+n+'\\([^]*?^}', 'm'))[0];
const ctx={G:{cosmetics:{},shells:123,decor:{cattree:2}},cats:[],_arranging:true,editRemember:()=>{},editBar:()=>{},rebuildAttractors:()=>{},save:()=>{},syncHud:()=>{},toast:()=>{}};
vm.createContext(ctx);
vm.runInContext(['itemStored','setItemStored','putAwayItem'].map(fn).join('\n'),ctx);
vm.runInContext('putAwayItem("decor","cattree:1","Cat tree")',ctx);
assert.equal(ctx.G.shells,123); assert.equal(ctx.G.decor.cattree,2);
assert(vm.runInContext('itemStored("decor","cattree:1")',ctx));
assert(!vm.runInContext('itemStored("decor","cattree:0")',ctx));
ctx.G=JSON.parse(JSON.stringify(ctx.G));
assert(vm.runInContext('itemStored("decor","cattree:1")',ctx));
vm.runInContext('setItemStored("decor","cattree:1",false)',ctx);
assert(!vm.runInContext('itemStored("decor","cattree:1")',ctx));
assert.equal(ctx.G.shells,123); assert.equal(ctx.G.decor.cattree,2);
vm.runInContext('putAwayItem("prop","lantern","Lantern")',ctx);
assert.equal(ctx.G.cosmetics.propBoxed.lantern,true);
assert(html.includes('if (itemStored("decor", dkey)) continue'));
assert(html.includes('if (itemStored("decor", w.dkey)) continue'));
assert(html.includes('if (itemStored("comfort", type + ":" + i)) continue'));
assert(html.includes('setItemStored(soldKey.kind, soldKey.key, false)'));
console.log('PASS: storage retains ownership and shells, persists through reload, restores free, isolates copies, filters world objects, and clears sold storage keys.');
