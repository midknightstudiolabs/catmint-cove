// Café pacing simulation: how long do the goals take for different kinds of players?
// Uses the engine's real constants (prices, intervals, ingredient costs/yields) with a simple, explicit player model.
// Run: node scripts/sim-cafe-pacing.mjs
await import('../ui/cafe-engine.js');
const E = globalThis.CoveCafeEngine;
const HOUR = 3600e3, DAY = 24 * HOUR, CAP = 12 * HOUR;   // settle() never banks more than 12h offline
const ING = E.ingredients, R = Object.fromEntries(E.recipes.map(r => [r.id, r]));

// what a visit does: harvest all patches, replant, top up the pantry
function simulate({ visitsPerDay, patches = 4, days = 400, goalsOrder }) {
  const stock = { coffee: 6, catmint: 6, honey: 2, carrot: 0 };
  const s = { speed: 0 }; let shells = 0, t = 0, lastSettle = 0, served = 0, spent = 0;
  const owned = new Set(); const log = [];
  const menu = ['coffee', 'tea', 'midknight'];   // a typical established menu
  const goals = goalsOrder.slice();
  const visitTimes = []; for (let d = 0; d < days; d++) for (let v = 0; v < visitsPerDay; v++) visitTimes.push(d * DAY + (8 + (v + .5) * (14 / visitsPerDay)) * HOUR);
  let plantedAt = -1e12;
  for (const vt of visitTimes) {
    // guests served since last visit (bank at most 12h), limited by stock
    const window = Math.min(vt - lastSettle, CAP), guests = Math.floor(window / E.interval(s));
    for (let g = 0; g < guests; g++) {
      const avail = menu.filter(id => Object.entries(R[id].inputs).every(([k, n]) => (stock[k] || 0) >= n));
      if (!avail.length) break;
      const id = avail[(served + g) % avail.length], r = R[id];
      for (const [k, n] of Object.entries(r.inputs)) stock[k] -= n;
      shells += r.price; served++;
    }
    lastSettle = vt;
    // garden: harvest what has grown (one crop cycle per visit), replant the two ingredients the menu burns fastest
    if (vt - plantedAt >= 900e3) {
      const per = Math.floor(patches / 2) || 1;
      const cost = per * ING.coffee.cost + (patches - per) * ING.honey.cost;
      if (shells >= cost || patches) { shells -= Math.min(shells, cost); spent += cost; stock.coffee += per * ING.coffee.yield; stock.honey += (patches - per) * ING.honey.yield * (vt - plantedAt >= 1500e3 ? 1 : 0); plantedAt = vt; }
    }
    if (stock.catmint < 4) { const buy = 10, cost = buy * ING.catmint.import; if (shells >= cost) { shells -= cost; stock.catmint += buy; spent += cost; } }
    // spend on goals in order when affordable
    while (goals.length && shells >= goals[0].cost) { const g = goals.shift(); shells -= g.cost; log.push({ goal: g.label, day: +(vt / DAY).toFixed(1) }); if (g.id === 'speed') s.speed++; if (g.id === 'patch') patches++; }
    if (!goals.length) break;
  }
  return { log, served, shells: Math.round(shells), spent };
}

const goals = () => [
  { id: 'seat', label: 'Table by the sea', cost: 150 }, { id: 'cookware', label: 'Copper cookware', cost: 180 },
  { id: 'speed', label: 'Twin brewer', cost: 300 }, { id: 'speed', label: 'Cove brewer', cost: 600 },
  ...Object.values(E.decor).map(d => ({ id: 'decor', label: d.name, cost: d.cost })),
  { id: 'shop', label: 'Garden Café', cost: E.shops[1].cost }, { id: 'shop', label: 'Seaside Café', cost: E.shops[2].cost },
].sort((a, b) => a.cost - b.cost);

const out = ['# Café pacing simulation (generated by scripts/sim-cafe-pacing.mjs)', '', 'Model: menu of Coastal Coffee, Catmint Cloud and Midknight Morning; guests every 4 / 3.5 / 3 min by brewer level; 4 garden patches (coffee and honey replanted each visit; catmint bought); offline banking capped at 12 h; each visit spends all Shells on the next goal in cost order. Real prices and ingredient costs from the engine.', ''];
for (const [name, visits] of [['Casual: 2 visits a day', 2], ['Regular: 4 visits a day', 4], ['Devoted: 8 visits a day', 8]]) {
  const r = simulate({ visitsPerDay: visits, goalsOrder: goals() });
  out.push(`## ${name}`, '', '| Goal | Reached on day |', '|---|---|', ...r.log.map(l => `| ${l.goal} | ${l.day} |`), '', `Guests served: ${r.served}. Seed and import spend: ${r.spent} Shells.`, '');
}
console.log(out.join('\n'));
